// Generates apps/web/app/lib/world-map.data.ts: SVG paths of the world's countries, for the
// region map. The map is drawn from public-domain Natural Earth data (via world-atlas), so the
// site needs no map tiles or map service. Countries with a region key get their own path; the
// rest of the world is one grey shape. Run after adding a country to REGIONS:
//   npm run build -w @isgratis/types && node scripts/generate-map-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoEqualEarth, geoPath } from 'd3-geo';
import { feature, merge } from 'topojson-client';
import { REGIONS } from '../packages/types/dist/index.js';

const require = createRequire(import.meta.url);
const atlas = (name) => JSON.parse(readFileSync(require.resolve(`world-atlas/${name}`), 'utf8'));

// ISO 3166-1 numeric codes of the countries in REGIONS.
const NUMERIC = {
  NL: '528', BE: '056', DE: '276', AT: '040', CH: '756', FR: '250', ES: '724', IT: '380', PT: '620',
  GB: '826', IE: '372', US: '840', CA: '124', DK: '208', NO: '578', SE: '752', FI: '246', PL: '616',
  LU: '442', EE: '233', ID: '360',
};
// Member states of the EU, drawn as one area for the EU key.
const EU = ['040', '056', '100', '191', '196', '203', '208', '233', '246', '250', '276', '300', '348', '372', '380',
  '428', '440', '442', '470', '528', '616', '620', '642', '703', '705', '724', '752'];

const WIDTH = 960;
const HEIGHT = 470;
// The coarse 110m data keeps the file small; small countries it leaves out (Luxembourg) come
// from the 50m data.
const topology = atlas('countries-110m.json');
const detailed = atlas('countries-50m.json');
const geometries = topology.objects.countries.geometries.filter((g) => g.id !== '010'); // no Antarctica
const world = { type: 'FeatureCollection', features: geometries.map((g) => feature(topology, g)) };
const shape = (code) => {
  const coarse = geometries.find((g) => g.id === code);
  if (coarse) return feature(topology, coarse);
  const fine = detailed.objects.countries.geometries.find((g) => g.id === code);
  return fine ? feature(detailed, fine) : null;
};
const projection = geoEqualEarth().fitExtent([[4, 4], [WIDTH - 4, HEIGHT - 4]], world);
const path = geoPath(projection);
const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 2) / 2)).replace(/(\D)0\./g, '$1.');

const paths = {};
for (const region of REGIONS) {
  const code = NUMERIC[region];
  if (!code) continue;
  const found = shape(code);
  if (!found) throw new Error(`No map shape for ${region} (${code})`);
  paths[region] = round(path(found));
}
paths.EU = round(path(merge(topology, geometries.filter((g) => EU.includes(g.id)))));
const rest = round(path(merge(topology, geometries.filter((g) => !Object.values(NUMERIC).includes(g.id)))));
// Bounding boxes of the main part of each country, to zoom the map in on them.
const bounds = {};
// Small countries get a dot so they can be clicked.
const centroids = Object.fromEntries(
  Object.keys(NUMERIC).map((region) => {
    // The largest part of the country: overseas territories would pull the centre into the sea.
    const found = shape(NUMERIC[region]);
    const parts =
      found.geometry.type === 'MultiPolygon'
        ? found.geometry.coordinates.map((coordinates) => ({ type: 'Polygon', coordinates }))
        : [found.geometry];
    const main = parts.reduce((a, b) => (path.area(b) > path.area(a) ? b : a));
    const [x, y] = path.centroid(main);
    const [[x0, y0], [x1, y1]] = path.bounds(main);
    bounds[region] = [x0, y0, x1, y1].map((n) => Math.round(n));
    return [region, [Math.round(x), Math.round(y)]];
  }),
);

const out = `// Generated by scripts/generate-map-data.mjs from Natural Earth (public domain). Do not edit.
export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};
export const REST_OF_WORLD = ${JSON.stringify(rest)};
export const REGION_PATHS: Record<string, string> = ${JSON.stringify(paths, null, 0)};
export const REGION_CENTROIDS: Record<string, [number, number]> = ${JSON.stringify(centroids)};
export const REGION_BOUNDS: Record<string, [number, number, number, number]> = ${JSON.stringify(bounds)};
`;
writeFileSync(new URL('../apps/web/app/lib/world-map.data.ts', import.meta.url), out);
console.log(`world-map.data.ts: ${(out.length / 1024).toFixed(0)} kB`);
