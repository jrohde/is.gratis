const MESSAGES: Record<Language, Messages> = { nl, en, de, es };

export function messages(lang: Language): Messages {
  return MESSAGES[lang];
}

export const LANGUAGE_NAMES: Record<Language, string> = {
  nl: 'Nederlands',
  en: 'English',
  de: 'Deutsch',
  es: 'Español',
};

const LOCALES: Record<Language, string> = { nl: 'nl-NL', en: 'en-GB', de: 'de-DE', es: 'es-ES' };

/**
 * Dates in UTC, so the server and the browser render the same text whatever the visitor's time
 * zone (a different day around midnight would break hydration).
 */
export function formatDate(iso: string, lang: Language): string {
  return new Intl.DateTimeFormat(LOCALES[lang], { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }).format(
    new Date(iso),
  );
}

export function formatNumber(value: number, lang: Language): string {
  return new Intl.NumberFormat(LOCALES[lang]).format(value);
}

/** Euro amounts from cents, without decimals when they are whole. */
export function formatPrice(cents: number, lang: Language): string {
  return new Intl.NumberFormat(LOCALES[lang], {
    style: 'currency',
    currency: 'EUR',
    minimumFractionDigits: cents % 100 === 0 ? 0 : 2,
  }).format(cents / 100);
}
